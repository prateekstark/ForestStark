"""The hardware interface each robot's drivers must serve, generated from the simulation bridge.

The autonomy stack talks to Gazebo only through the topics in sim.bridge_entries; on a machine the
drivers serve exactly those topics, so this table is the contract between the two. Joint ranges
and limits come from the URDF the simulator loads.

    ros2 run fs_bringup interface_contract --out docs/hardware_interface.md
"""
import argparse
import xml.etree.ElementTree as ET
from pathlib import Path

from fs_bringup import sim

SIM_ONLY = {"ground_truth"}
ABOUT = {
    "odometry": ("odom", "wheel / track odometry in the robot's odom frame, 50 Hz"),
    "imu": ("imu", "chassis IMU, 100 Hz, gravity included"),
    "imu_rear": ("imu_rear", "rear-unit IMU (articulation and tip-over), 100 Hz"),
    "gnss": ("gnss/fix_raw", "receiver fix with covariance, 5-10 Hz; RTK fix as STATUS_GBAS_FIX"),
    "joint_states": ("joint_states", "every joint of the URDF, 50 Hz (robot_state_publisher builds TF from it)"),
    "auger/status": ("auger/status", "JSON, 20 Hz: phase (idle lowering boring bored refusal no_ground retracting "
                     "stopped held), depth, collapse, open_depth, target, stroke, feed, thrust, torque, power, "
                     "energy_kj, thrust_limited, in_rock, in_pan, hole [x, y]"),
    "plugs/status": ("plugs/status", "JSON, 5 Hz: per carrier count, cells, next, occ ('1' per full cell), "
                     "next_local / next_angle; per holder whether it holds a plug"),
    "terramechanics": ("terramechanics", "JSON, 10 Hz: per wheel load N, sinkage z, slip, rut; mean slip, "
                       "motion resistance (on a machine: from drive currents and the odometry / GNSS speed)"),
    "cmd_vel": ("cmd_vel", "Twist from the safety monitor only; the drive stops if none arrives for 0.5 s"),
    "auger/cmd": ("auger/cmd", "\"bore <m>\" | \"pick <m>\" | \"retract\" | \"stop\" | \"hold\" | \"resume\" | "
                  "\"wet <litres>\"; the feed controller stops on refusal (rock) and reports it"),
    "plugs/cmd": ("plugs/cmd", "\"pick <carrier> <cell|next> <holder>\" | \"move <from> <to>\" | \"drop <holder>\" | "
                  "\"fill <carrier> [n]\" | \"empty <carrier> [n]\""),
}


def joint_limits(kind: str) -> dict:
    urdf = ET.fromstring(sim.robot_description(kind, kind, Path("/tmp/none.soilmap"), lidar=True))
    out = {}
    for j in urdf.findall("joint"):
        lim = j.find("limit")
        if lim is not None:
            out[j.get("name")] = (j.get("type"), lim.get("lower", "-"), lim.get("upper", "-"),
                                  lim.get("effort", "-"), lim.get("velocity", "-"))
    return out


def contract(kind: str) -> str:
    entries = sim.bridge_entries(kind, "NS", lidar=True)
    lines = [f"## {kind.capitalize()}", "", "| Topic (in the robot's namespace) | Type | Driver | Contents |", "|---|---|---|---|"]
    for e in entries:
        g = e["gz_topic_name"].split("/model/NS/")[1]
        r = e["ros_topic_name"].split("/NS/")[1]
        if g in SIM_ONLY or g.startswith("joint/"):
            continue
        about = ABOUT.get(g, (r, "planar lidar, 10 Hz, in its own frame from the URDF" if "scan" in g else ""))[1]
        about = about.replace("|", "\\|")
        lines.append(f"| `{r}` | `{e['ros_type_name']}` | {'publishes' if e['direction'] == 'GZ_TO_ROS' else 'subscribes'} "
                     f"| {about} |")
    lim = joint_limits(kind)
    lines += ["", "Position commands (`std_msgs/msg/Float64` on `joint/<name>/cmd_pos`, driver subscribes; m or rad):", "",
              "| Joint | Type | Lower | Upper | Effort (N or N m) | Velocity |", "|---|---|---|---|---|---|"]
    for j in sim.JOINT_CMDS[kind]:
        t, lo, hi, ef, ve = lim.get(j, ("?", "-", "-", "-", "-"))
        lines.append(f"| `{j}` | {t} | {lo} | {hi} | {ef} | {ve} |")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="")
    a, _ = ap.parse_known_args()
    text = ("# Hardware interface\n\nGenerated by `ros2 run fs_bringup interface_contract` from the topics the "
            "simulator bridges (`fs_bringup/sim.py`) and the joint limits in the URDF. A machine's drivers serve "
            "these topics under the robot's namespace and `ros2 launch fs_bringup robot.launch.py` runs the same "
            "autonomy nodes the simulator tests. Frames: `<ns>/base_link` etc. from robot_state_publisher; "
            "`map` is the site's ENU frame at the surveyed origin.\n\n"
            + "\n".join(contract(k) for k in ("katar", "jaal", "pahadi")))
    print(text)
    if a.out:
        Path(a.out).write_text(text)


if __name__ == "__main__":
    main()
