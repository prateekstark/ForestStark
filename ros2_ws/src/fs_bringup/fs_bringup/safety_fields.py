"""Scanner field sets for each robot's certified safety layer, for the scanner configuration tool.

    ros2 run fs_bringup safety_fields --out ../docs/safety_fields.md

Writes the Markdown report and, beside it, safety_fields.yaml: every field set as a polygon in
base_link and in each safety scanner's own frame (scanner poses from the URDF the robot runs), so
the commissioning engineer enters computed numbers, not drawn ones. The sizing is in
fs_autonomy.safety_fields; the reasoning is in docs/safety_concept.md.
"""
from __future__ import annotations

import argparse
import math
from pathlib import Path

import numpy as np
import yaml

from fs_autonomy import safety, safety_fields as sf
from fs_bringup import sim
from fs_bringup.physics_audit import Model


def scanners(kind: str) -> dict:
    """Scanner name -> (x, y, yaw) in base_link, for the lidars the robot's safety layer uses."""
    m = Model(sim.robot_description(kind, kind, Path("/tmp/none.soilmap"), lidar=True))
    out = {}
    for link in m.joints:                  # child links (scanner links carry no inertia)
        if "lidar" in link or "scan" in link:
            T = m.T(link)
            out[link] = (float(T[0, 3]), float(T[1, 3]), math.atan2(T[1, 0], T[0, 0]))
    return out


def to_frame(poly: np.ndarray, pose) -> list:
    x, y, th = pose
    c, s = math.cos(th), math.sin(th)
    d = poly - np.array([x, y])
    return [[round(float(c * px + s * py), 3), round(float(-s * px + c * py), 3)] for px, py in d]


def report() -> tuple:
    lines = ["# Safety scanner field sets", "",
             "Generated by `ros2 run fs_bringup safety_fields` (sizing in `fs_autonomy/safety_fields.py`, reasoning in "
             "[safety_concept.md](safety_concept.md)). Protective field length beyond the footprint "
             "`S = v T + 1.1 v^2 / 2a + Z`. Polygons for every field set, in base_link and in each scanner's frame, are in "
             "`safety_fields.yaml`.", ""]
    data = {}
    for kind in ("jaal", "pahadi", "katar"):
        ch = sf.CHAINS[kind]
        cfg = safety.SafetyConfig.for_robot(kind)
        sc = scanners(kind)
        lines += [f"## {kind.capitalize()}", "",
                  f"Stop chain: scanner {ch.scanner_s * 1000:.0f} ms + PLC {ch.plc_s * 1000:.0f} ms + drives "
                  f"{ch.drive_s * 1000:.0f} ms = {ch.T * 1000:.0f} ms; SS1 deceleration {ch.decel} m/s^2; "
                  f"Z = {ch.z} m; {ch.side} m beside the footprint. Scanners: "
                  + (", ".join(f"`{n}` at ({p[0]:+.2f}, {p[1]:+.2f}) m, yaw {math.degrees(p[2]):+.0f} deg" for n, p in sc.items()) or "none")
                  + ".", ""]
        sets = sf.field_sets(kind)
        if sets:
            lines += ["| Field set | Speed up to | Stopping distance | Protective field ahead | Warning field ahead | "
                      "Comfort layer stops for a person / object at |", "|---|---|---|---|---|---|"]
            for s in sets:
                if s.direction not in ("+x",):
                    continue
                v = s.band
                floor = sf.protective_length(v, ch) + cfg.chain_margin
                static_stop = max(floor, max(cfg.stop_min, min(cfg.stop_static, 0.4 + v * v / (2 * cfg.decel)))) if cfg.stop_static else 0
                lines.append(f"| {s.name} | {v:.1f} m/s | {sf.stopping_distance(v, ch):.2f} m | {sf.protective_length(v, ch):.2f} m | "
                             f"{sf.protective_length(v, ch) + sf.WARN_S * v + 0.5:.2f} m | {max(cfg.stop_person, floor):.1f} m / {static_stop:.1f} m |")
            dirs = sorted({s.direction for s in sets})
            if len(dirs) > 1:
                lines.append(f"\nThe same bands are switched for travel along {', '.join(dirs)} (swerve drive: front and rear scanners).")
        else:
            lines.append("The tractor is driven by its driver: no travel fields. The certified layer guards the tool.")
        lines += ["", f"Tool zone: {sf.TOOL_R:.1f} m around the tool while the auger turns or feeds -> STO on the tool drives.", ""]
        data[kind] = {
            "stop_chain": {"scanner_s": ch.scanner_s, "plc_s": ch.plc_s, "drive_s": ch.drive_s, "decel": ch.decel, "z": ch.z},
            "scanners": {n: {"x": p[0], "y": p[1], "yaw": p[2]} for n, p in sc.items()},
            "standstill": {"base_link": sf.standstill(kind).round(3).tolist()},
            "field_sets": [{"name": s.name, "speed_max": s.band, "direction": s.direction,
                            "protective": {"base_link": s.protective.round(3).tolist(),
                                           **{n: to_frame(s.protective, p) for n, p in sc.items()}},
                            "warning": {"base_link": s.warning.round(3).tolist(),
                                        **{n: to_frame(s.warning, p) for n, p in sc.items()}}} for s in sets],
            "tool_zone_radius": sf.TOOL_R,
        }
    lines += ["## In normal operation", "",
              "The comfort layer (the software safety monitor) slows from 6 m and stops for a person in the path at 2.5-3 m, "
              "for an object at 0.5-1.5 m depending on speed; the protective fields are shorter at every speed the "
              "navigators use, so the certified layer only acts when the software has not (a fault, a person stepping "
              "out from behind something within its reach). The simulator runs the PLC logic on the same scans "
              "(`plc_model`) and counts its trips: in normal runs there should be none.", ""]
    return "\n".join(lines) + "\n", data


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="")
    a, _ = ap.parse_known_args()
    text, data = report()
    print(text)
    if a.out:
        Path(a.out).write_text(text)
        Path(a.out).with_suffix(".yaml").write_text(yaml.safe_dump(data, sort_keys=False))


if __name__ == "__main__":
    main()
