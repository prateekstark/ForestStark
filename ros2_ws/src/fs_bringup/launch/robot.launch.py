"""One ForestStark robot on its own hardware: the autonomy stack without Gazebo.

    ros2 launch fs_bringup robot.launch.py robot:=katar site_file:=/data/site/nh48_km112.yaml
    ros2 launch fs_bringup robot.launch.py robot:=jaal ns:=jaal_2 fleet:=jaal_1,jaal_2,jaal_3 site_file:=...
    ros2 launch fs_bringup robot.launch.py robot:=pahadi region:=himalayan_midhills site_file:=...

The drivers on the machine serve the hardware interface (docs/hardware_interface.md, generated by
`ros2 run fs_bringup interface_contract`): the same topics the Gazebo bridge serves in simulation,
so every node here is the one the simulator tests. The site file is the surveyed site YAML with its
soil map next to it (same format as the generated simulation sites).

Arguments
  robot         katar | jaal | pahadi
  site_file     surveyed site YAML (required)
  ns            robot namespace (the robot's name; jaal_1.. for a Jaal fleet)
  region        planting region (default: the site's, else the robot's default)
  spacing       m between plants (the region's)
  fleet         Jaal: comma-separated fleet the robot shares the field with
  fleet_manager Jaal: also run the fleet manager here (base-station PC: true)
  field         Jaal: demo | full
  deep_auger    Katar: true when the 1.45 m auger kit is fitted
  mode          Katar: stop_and_go | on_the_move
  log_dir       where planting records go (default ~/.ros/fs_logs)
  rviz          false on the robot; true on an operator laptop on the same network
"""
from pathlib import Path

import yaml
from launch import LaunchDescription
from launch.actions import DeclareLaunchArgument, OpaqueFunction
from launch_ros.actions import Node

from fs_bringup import sim

ARGS = {"robot": "katar", "site_file": "", "ns": "", "region": "", "spacing": "", "fleet": "", "fleet_manager": "false",
        "field": "full", "deep_auger": "false", "mode": "stop_and_go", "rail_min": "-1.8", "rail_max": "0.6",
        "speed_kmh": "2.5", "rows": "3", "side": "downhill", "half_moon": "true", "log_dir": "", "rviz": "false"}
SITES = {"katar": "roadside", "jaal": "open_field", "pahadi": "hill_slope"}


def setup(context):
    c = context.launch_configurations
    kind = c["robot"]
    if kind not in SITES:
        raise RuntimeError(f"robot must be one of {', '.join(SITES)}")
    if not c["site_file"]:
        raise RuntimeError("site_file:= the surveyed site YAML is required on a robot")
    site_file = Path(c["site_file"]).expanduser().resolve()
    site = yaml.safe_load(site_file.read_text())
    c = {**c, "region": c["region"] or site.get("region", "")}
    region, spacing, row_spacing = sim.region_setup(kind, SITES[kind], c)
    ns = c["ns"] or ("jaal_1" if kind == "jaal" else kind)
    common = {"site_file": str(site_file), "robot": ns, "use_sim_time": False}
    deep = sim.on(c["deep_auger"])

    desc = sim.robot_description(kind, ns, site_file.parent / site["soil_map"], lidar=True,
                                 xacro_args={"deep_auger": "true" if deep else "false"} if kind == "katar" else None)
    head = sim.head_params(kind, region=region, spawn_models=False)
    if kind == "katar":
        head.update(deep_auger=deep, rail_min=float(c["rail_min"]), rail_max=float(c["rail_max"]))
    fleet = [r for r in c["fleet"].split(",") if r] or [ns]

    actions = [Node(package="robot_state_publisher", executable="robot_state_publisher", namespace=ns, output="log",
                    parameters=[{"robot_description": desc, "frame_prefix": f"{ns}/", "use_sim_time": False}])]
    actions += sim.robot_core(kind, ns, site_file, site["name"], head, gnss_mode="receiver", lidar=True,
                              peers=fleet if kind == "jaal" else (), sim_time=False)
    if kind == "katar":
        actions.append(Node(package="fs_autonomy", executable="katar_planter", namespace=ns, output="screen",
                            parameters=[{**common, "spacing": spacing, "mode": c["mode"], "surveyed": True,
                                         "speed_kmh": float(c["speed_kmh"]), "rail_min": float(c["rail_min"]),
                                         "rail_max": float(c["rail_max"])}]))
    elif kind == "jaal":
        cap = int(head["plugs"])
        actions.append(Node(package="fs_autonomy", executable="jaal_navigator", namespace=ns, output="screen",
                            parameters=[{**common, "robots": fleet, "field": c["field"], "use_lidar": True,
                                         "plugs_capacity": cap, **sim.robot_config("jaal", "navigator")}]))
        if sim.on(c["fleet_manager"]):
            actions.append(Node(package="fs_autonomy", executable="jaal_fleet_manager", output="screen",
                                parameters=[{"site_file": str(site_file), "robots": fleet, "field": c["field"],
                                             "spacing": spacing, "plugs_per_robot": cap, "out_dir": c["log_dir"],
                                             "use_sim_time": False}]))
    else:
        actions += [
            Node(package="fs_autonomy", executable="stability_monitor", namespace=ns, output="screen",
                 parameters=[{**common, "contact_links": sim.PAHADI_CONTACTS,
                              "contact_parents": ["base_link" if n.startswith("f") else "rear_link"
                                                  for n in sim.PAHADI_CONTACTS], "wheel_radius": 0.21}]),
            Node(package="fs_autonomy", executable="pahadi_navigator", namespace=ns, output="screen",
                 parameters=[{**common, "rows": int(c["rows"]), "row_spacing": row_spacing, "spacing": spacing,
                              "side": c["side"], "half_moon": sim.on(c["half_moon"])}]),
        ]
    actions += sim.common_nodes(site_file, sim.on(c["rviz"]), f"{kind}.rviz", c["log_dir"], sim_time=False)
    return actions


def generate_launch_description():
    return LaunchDescription([*[DeclareLaunchArgument(k, default_value=v) for k, v in ARGS.items()],
                              OpaqueFunction(function=setup)])
